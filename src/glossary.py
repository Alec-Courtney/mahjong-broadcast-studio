# Keep every pre-existing ID and canonical bilingual string unchanged: saved
# favourites/buttons and exact title/body translations continue to resolve.
_merged = []
for _entry in GLOSSARY:
    _entry = dict(_entry)
    _identity = _entry['id']
    _entry['aliases'] = tuple(dict.fromkeys(_entry['aliases']+_M_LEAGUE_ALIASES.get(_identity, ())))
    _codes = tuple(code for code, caption in M_LEAGUE_CAPTIONS.items() if caption['term_id'] == _identity)
    if _codes:
        _entry['broadcast_evidence'] = _codes
        _entry['source_ids'] += tuple('mleague_'+code.lower() for code in _codes)
        _entry['sources'] = tuple(dict.fromkeys(_entry['sources']+tuple(M_LEAGUE_CAPTIONS[code]['source_url'] for code in _codes)))
    if _identity in _M_LEAGUE_VISIBLE:
        _entry.update(category=_M_LEAGUE_VISIBLE[_identity], legacy=False)
    _merged.append(_entry)
GLOSSARY = tuple(_merged)+_M_LEAGUE_NEW

_BY_ID = {term['id']: term for term in GLOSSARY}


def get_term(term_id):
    """Return a registered entry, or None for an unknown/non-string ID."""
    return _BY_ID.get(term_id) if isinstance(term_id, str) else None


def terms_for_category(category=None, include_legacy=False):
    """None/empty returns available commentary; compatibility-only entries hide."""
    return tuple(term for term in GLOSSARY
                 if (include_legacy or not term['legacy'])
                 and (not category or term['category'] == category))


def term_text(term_id, language='zh_CN'):
    """Return the registered title/body in the selected presentation language."""
    term = get_term(term_id)
    if term is None:
        return ('', '')
    prefix = 'ja' if language in ('ja', 'ja_JP', '日本語') else 'zh'
    return term[prefix + '_title'], term[prefix + '_body']


def resolve_term_id(title, body=None):
    """Resolve exact registered text; edited/custom same-name bodies never match.

    Aliases are accepted for a title-only lookup. A title/body lookup accepts
    only registered Chinese/Japanese titles and a matching registered body.
    Never fuzzy-match a saved custom sentence or infer an ID from its title alone.
    """
    if not isinstance(title, str):
        return None
    for term in GLOSSARY:
        titles = (term['zh_title'], term['ja_title'])
        if body is None:
            if title in titles + term['aliases']:
                return term['id']
        elif title in titles and body in (term['zh_body'], term['ja_body']):
            return term['id']
    return None


def translation_pairs():
    """Exact canonical Chinese -> Japanese strings, including legacy snapshots."""
    pairs = {}
    for term in GLOSSARY:
        pairs[term['zh_title']] = term['ja_title']
        pairs[term['zh_body']] = term['ja_body']
    for category in CATEGORIES:
        pairs[category['zh_title']] = category['ja_title']
    return pairs


def display_text(value, language='zh_CN'):
    """Translate exact canonical text only; unregistered text is untouched."""
    if language in ('ja', 'ja_JP', '日本語'):
        return translation_pairs().get(value, value)
    return value

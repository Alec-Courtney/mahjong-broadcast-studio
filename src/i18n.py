_JA.update({'队徽':'チームロゴ','选择队徽':'チームロゴを選択','清除队徽':'チームロゴを解除','清除照片':'写真を解除'})
_ZH = {ja:zh for zh,ja in _JA.items() if ja != zh}

_DIRECTIONS = {'东': '東', '南': '南', '西': '西', '北': '北'}
_CACHED_FIELDS = '_mahjong_i18n_fields'


def _dynamic(value):
    # Full templates preserve the unknown portions (names/titles) verbatim.
    if value.endswith('以上'):
        threshold = value[:-2].rstrip()
        if re.fullmatch(r'(?:[\d,]+(?: / [\d,]+)?(?: ALL)?|单倍役满|\d+倍役满)', threshold):
            return tr(threshold)+'以上'
    if value in ('自摸条件','荣和条件','冠军条件','半决赛晋级条件','决赛晋级条件'):
        return {'自摸条件':'ツモ条件','荣和条件':'ロン条件','冠军条件':'優勝条件',
                '半决赛晋级条件':'準決勝進出条件','决赛晋级条件':'決勝進出条件'}[value]
    stage = re.fullmatch(r'第(\d+)轮晋级条件', value)
    if stage:return f'第{stage[1]}ラウンド進出条件'
    if ' / ' in value:
        parts=value.split(' / ')
        if all(part in _JA for part in parts):return ' / '.join(_JA[part] for part in parts)
    m = re.fullmatch(r'前(\d+)(名|队)晋级', value)
    if m:return f'上位{m[1]}{ "チーム" if m[2] == "队" else "名" }通過'
    m = re.fullmatch(r'前(\d+)(名|队)晋级 · 已结算排名', value)
    if m:
        return f'上位{m[1]}{ "チーム" if m[2] == "队" else "名" }通過 · 確定順位'
    m = re.fullmatch(r'([\d,]+) ALL', value)
    if m:return m[1]+'オール'
    m = re.fullmatch(r'前(\d+)(名|队)晋级 · 本局结束试算', value)
    if m:
        return f'上位{m[1]}{ "チーム" if m[2] == "队" else "名" }通過 · 本局終了時の試算'
    m = re.fullmatch(r'已记录 (\d+) 局\s*已入账 (\d+) 场(?:\s*当前局点数与赛事积分自动联动)?', value)
    if m:
        return f'{m[1]}局を記録　{m[2]}対局を確定'
    m = re.fullmatch(r'已记录 (\d+) 局\s*·\s*流局 (\d+) 局', value)
    if m:
        return f'記録済み {m[1]}局 · 流局 {m[2]}局'
    m = re.fullmatch(r'总局数\s*/\s*(\d+)\s*局\s*流局数\s*/\s*(\d+)\s*局', value)
    if m:
        return f'総局数 / {m[1]}局　流局数 / {m[2]}局'
    m = re.fullmatch(r'(\d+)\s*进\s*([123])', value)
    if m:
        return f'{m[1]}人中{m[2]}人通過'
    m = re.fullmatch(r'([东南西北])\s*(\d+)\s*局(.*)', value)
    if m:
        return _DIRECTIONS[m[1]]+' '+m[2]+' 局'+re.sub(r'(\d+)\s*本场',r'\1本場',m[3])
    m = re.fullmatch(r'(\d+)\s*倍役满', value)
    if m:
        return m[1]+'倍役満'
    if value == '单倍役满':return '役満'
    m = re.fullmatch(r'(宝牌|赤宝牌|里宝牌|立直|和牌|放铳)\s+(\d+)', value)
    if m:
        return _JA[m[1]]+' '+m[2]
    m = re.fullmatch(r'(席位|选手)\s*(\d+|[一二三四]|[ABCD])', value)
    if m:
        n = str('一二三四'.index(m[2])+1) if m[2] in '一二三四' else m[2]
        return ('座席 ' if m[1]=='席位' else '選手 ')+n
    m = re.fullmatch(r'(\d+)\s*档', value)
    if m:
        return m[1]+' 通り'
    m = re.fullmatch(r'(\d+)\s*场', value)
    if m:
        return m[1]+' 対局'
    if value in (' 秒', ' 张'):
        return ' 秒' if value==' 秒' else ' 枚'
    m = re.fullmatch(r'([一二三四五六七八九]|赤五)([万筒索])',value)
    if m:
        n='赤5' if m[1]=='赤五' else str('一二三四五六七八九'.index(m[1])+1)
        return n+{'万':'萬','筒':'筒','索':'索'}[m[2]]
    m = re.fullmatch(r'(\d+)番',value)
    if m:return m[1]+'翻'
    m = re.fullmatch(r'(副露|听牌|宝牌|吃|碰|明杠|暗杠|加杠) · (.*)',value)
    if m:
        return tr(m[1])+' · '+(tr(m[2]) if m[1] in ('吃','碰','明杠','暗杠','加杠') else m[2])
    if value.startswith('荣和 · '):
        return 'ロン · '+value[len('荣和 · '):]
    if value.startswith('当前演示：'):
        return '現在のデモ：'+tr(value[len('当前演示：'):])
    if value.startswith('演示 · '):
        return 'デモ · '+tr(value[len('演示 · '):])
    if value.startswith('麻将UI · '):
        return '麻雀UI · '+tr(value[len('麻将UI · '):])
    if value.startswith('移除'):
        return '削除 '+tr(value[2:])
    if value.startswith('自摸 '):
        tail=value[3:]
        tail=_JA.get(tail,tail)
        tail=re.sub(r'([\d,]+) ALL',r'\1オール',tail)
        tail=re.sub(r'；对(.+?)荣和([\d,]+)',r'；\1からロン\2',tail)
        tail=re.sub(r'\s*等(\d+)档',r' ほか計\1通り',tail)
        return 'ツモ '+tail
    for suffix,replacement in [
        ('必须是有效范围内的数字','は有効な範囲内の数値にしてください'),
        ('必须是整数','は整数で入力してください'),
        ('不能为负数','は0以上で入力してください'),
        ('必须为开或关','はオン・オフで指定してください'),
        ('必须是 0 到 3 的座位编号','は0～3の座席番号で指定してください'),
        ('的颜色无效，请填写如 #377e72','の色が無効です。例：#377e72'),
    ]:
        if value.endswith(suffix):
            return tr(value[:-len(suffix)])+replacement
    for prefix,replacement in [('未知转播模块：','不明な配信パネル：'),('不支持的事件：','非対応のイベント：'),('牌面素材无法读取：','牌画像を読み込めません：'),('点棒素材无法读取：','点棒画像を読み込めません：')]:
        if value.startswith(prefix):return replacement+value[len(prefix):]
    # A compound UI label includes user text before the separator.
    for label in ('队伍排名','个人排名'):
        suffix='  ·  '+label
        if value.endswith(suffix):return value[:-len(suffix)]+'  ·  '+_JA[label]
    # Status strips contain numeric values and known separators only. Never
    # apply broad substitutions to an arbitrary user sentence.
    if value.startswith(('含本场试算 ', '已归档积分 ')):
        head,tail=value.split(' ',1);return _JA.get(head,head)+' '+tail
    return value


def tr(value, literal=False):
    """Translate a presentation string, never mutate model data."""
    value = str(value)
    if literal:return value
    if _language != 'ja_JP':
        return value
    return _JA.get(value) or _dynamic(value)


def _field(obj, key, getter, setter):
    """Remember source and last output; recognize fresh external UI updates."""
    current = getter()
    if not isinstance(current,str) or not current:
        return
    cache = getattr(obj, _CACHED_FIELDS, None)
    if cache is None:
        cache = {};setattr(obj,_CACHED_FIELDS,cache)
    original, rendered = cache.get(key, (_ZH.get(current,current), current))
    if current != rendered:
        original = _ZH.get(current,current)
    translated = tr(original)
    if current != translated:
        setter(translated)
    cache[key] = (original, translated)


def localize_widgets(root, seen=None):
    """Translate presentation properties only; reversible and idempotent.

    QLineEdit/QTextEdit values and editable table cells are deliberately kept
    in their original language. Set i18n_literal on a widget to skip it.
    """
    widgets = [root]+root.findChildren(QWidget)
    for w in widgets:
        if seen is not None:
            if w in seen:continue
            seen.add(w)
        if w.property('i18n_literal') or w.property('i18nLiteral'):
            continue
        blocker=QSignalBlocker(w)
        try:
            _field(w,'windowTitle',w.windowTitle,w.setWindowTitle)
            _field(w,'toolTip',w.toolTip,w.setToolTip)
            _field(w,'statusTip',w.statusTip,w.setStatusTip)
            if isinstance(w,(QLabel,QAbstractButton)):
                _field(w,'text',w.text,w.setText)
            if isinstance(w,QGroupBox):
                _field(w,'title',w.title,w.setTitle)
            if isinstance(w,QLineEdit):
                _field(w,'placeholder',w.placeholderText,w.setPlaceholderText)
            if isinstance(w,(QSpinBox,QDoubleSpinBox)):
                _field(w,'prefix',w.prefix,w.setPrefix)
                _field(w,'suffix',w.suffix,w.setSuffix)
                _field(w,'specialValueText',w.specialValueText,w.setSpecialValueText)
            if isinstance(w,QComboBox) and not w.isEditable():
                for i in range(w.count()):
                    _field(w,('item',i),lambda i=i:w.itemText(i),lambda text,i=i:w.setItemText(i,text))
            if isinstance(w,QTabWidget):
                for i in range(w.count()):
                    _field(w,('tab',i),lambda i=i:w.tabText(i),lambda text,i=i:w.setTabText(i,text))
            if isinstance(w,QListWidget):
                for i in range(w.count()):
                    item=w.item(i)
                    _field(item,'text',item.text,item.setText)
            if isinstance(w,QTreeWidget):
                def visit(item):
                    _field(item,'text',lambda:item.text(0),lambda text:item.setText(0,text))
                    for i in range(item.childCount()):visit(item.child(i))
                for i in range(w.topLevelItemCount()):visit(w.topLevelItem(i))
            if isinstance(w,(QMenu,QMenuBar)):
                for action in w.actions():_field(action,'text',action.text,action.setText)
            if isinstance(w,QTableWidget):
                for i in range(w.columnCount()):
                    item=w.horizontalHeaderItem(i)
                    if item is not None:_field(item,'text',item.text,item.setText)
        finally:
            del blocker


class LanguageController(QObject):
    """Coalesce Qt layout notifications instead of scanning on every frame."""
    def __init__(self, app=None):
        super().__init__(app or QApplication.instance())
        self.app=app or QApplication.instance();self.roots=[];self.pending=False;self.applying=False;self.translator=None;self.disposed=False
        if self.app:self.app.installEventFilter(self)
        signals.language_changed.connect(self.change_language)
        self.install_qt_language()
    def install_qt_language(self):
        if self.disposed:return
        QLocale.setDefault(QLocale(get_language()))
        if not self.app:return
        if self.translator is not None:self.app.removeTranslator(self.translator)
        self.translator=QTranslator(self)
        name='qtbase_ja' if get_language()=='ja_JP' else 'qtbase_zh_CN'
        if self.translator.load(name,QLibraryInfo.path(QLibraryInfo.LibraryPath.TranslationsPath)):
            self.app.installTranslator(self.translator)
    def change_language(self,*_):
        self.install_qt_language();self.refresh()
    def refresh(self):
        self.flush(include_hidden=True)
    def dispose(self):
        if self.disposed:return
        self.disposed=True;self.pending=False;self.roots=[]
        try:signals.language_changed.disconnect(self.change_language)
        except (RuntimeError,TypeError):pass
        if self.app:
            self.app.removeEventFilter(self)
            if self.translator is not None:self.app.removeTranslator(self.translator)
        self.translator=None
    def track(self, root):
        if not any(r() is root for r in self.roots):self.roots.append(weakref.ref(root))
        localize_widgets(root)
    def schedule(self,*_):
        if self.disposed or self.pending or self.applying:return
        self.pending=True;QTimer.singleShot(0,self.flush)
    def flush(self, *, include_hidden=False):
        self.pending=False
        if self.disposed or self.applying:return
        self.applying=True
        try:
            # Qt file dialogs also need their Chinese caller-supplied title.
            roots=[r() for r in self.roots if r() is not None]
            if self.app:
                roots.extend(w for w in self.app.topLevelWidgets() if include_hidden or w.isVisible())
            seen=set()
            for root in roots:
                if root in seen:continue
                try:localize_widgets(root,seen)
                except RuntimeError:pass  # a dialog closed while this flush was queued
        finally:self.applying=False
    def eventFilter(self,obj,event):
        # New forms already use Chinese source strings. Only Japanese needs
        # rescans on layout events. Explicit language changes still visit all.
        if _language=='ja_JP' and not self.disposed and not self.applying and event.type() in (QEvent.Type.Show,QEvent.Type.LayoutRequest,QEvent.Type.ChildAdded,QEvent.Type.WindowTitleChange,QEvent.Type.ToolTipChange):
            self.schedule()
        return False
